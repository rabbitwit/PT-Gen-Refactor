function detectLanguage() {
    const stored = localStorage.getItem('ptgen.language')
    if (stored && MESSAGES[stored]) return stored

    const candidates = navigator.languages?.length ? navigator.languages : [navigator.language]
    for (const raw of candidates) {
        const value = (raw || '').toLowerCase()
        if (value.startsWith('zh-tw') || value.startsWith('zh-hk') || value.startsWith('zh-hant')) return 'zh-TW'
        if (value.startsWith('zh')) return 'zh-CN'
        if (value.startsWith('ja')) return 'ja'
        if (value.startsWith('ko')) return 'ko'
        if (value.startsWith('en')) return 'en'
    }
    return 'zh-CN'
}

export function createTranslator(language) {
    const table = MESSAGES[language] ?? MESSAGES['zh-CN']

    /**
     * @param {string} key
     * @param {Record<string, string | number>} [variables]
     */
    function t(key, variables = {}) {
        const template = table[key] ?? MESSAGES.en[key] ?? key
        return template.replace(/\{(\w+)}/g, (_, name) => String(variables[name] ?? ''))
    }

    return t
}

